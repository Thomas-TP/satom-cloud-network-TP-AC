"""Module 9 : l'Application Load Balancer sur deux zones, avec le listener HTTPS 443 (certificat importe) vers tg-web."""
from common import *

async def run(r):
    await r.goto(ec2_url('CreateALBWizard:'), wait=6); await r.hold(1.5)
    await r.type(lambda f: f.locator('input[type=text]').first, 'alb-prod-leman-TP-AC'); await r.hold(0.8)
    r.mark('nom')
    await r.scroll(500); await r.hold(0.8)
    await r.click(lambda f: f.locator('button:has-text("vpc-05507")').first); await r.hold(1.0)
    await r.click(lambda f: f.get_by_role('option', name=re.compile('vpc-prod-leman-TP-AC')).first); await r.hold(2.5)
    await r.scroll(300); await r.hold(0.8)
    # zones : 1a et 1b avec leurs sous-reseaux publics
    r.mark('vpc')
    await r.click(lambda f: f.get_by_text('eu-north-1a', exact=False).first); await r.hold(1.5)
    await r.click(lambda f: f.get_by_text('eu-north-1b', exact=False).first); await r.hold(1.5)
    r.mark('zones'); await r.hold(1.5)
    await r.scroll(500); await r.hold(0.8)
    await r.click(lambda f: f.get_by_role('button', name=re.compile('^Supprimer default')).first); await r.hold(0.8)
    await r.click(lambda f: f.get_by_role('button', name=re.compile("Sélectionner jusqu'à 16 groupes")).first); await r.hold(1.0)
    await r.click(lambda f: f.get_by_role('option', name=re.compile('alb-TP-AC')).first); await r.hold(1.2)
    await r.press('Escape', 0.5)
    r.mark('sg')
    await r.scroll(350); await r.hold(0.8)
    await r.click(lambda f: f.get_by_text('Protocole', exact=True).first.locator('xpath=following::button[1]')); await r.hold(1.0)
    await r.click(lambda f: f.get_by_role('option', name=re.compile('^HTTPS')).first); await r.hold(1.2)
    r.mark('listener')
    await r.scroll(300); await r.hold(0.8)
    await r.click(lambda f: f.locator('button:has-text("Sélectionner un groupe cible")').first); await r.hold(1.2)
    await r.click(lambda f: f.get_by_role('option', name=re.compile('tg-web-TP-AC')).first); await r.hold(1.5)
    r.mark('groupe-cible')
    await r.scroll(600); await r.hold(0.8)
    await r.click(btn('Sélectionner un certificat')); await r.hold(1.2)
    await r.click(lambda f: f.get_by_role('option', name=re.compile('portefeuilles')).first); await r.hold(1.5)
    r.mark('certificat')
    await r.scroll(900); await r.hold(0.8)
    await r.click(lambda f: f.get_by_text('Équilibreur de charge balises').first); await r.hold(1.0)
    await tags(r, 'prod', start=0, add='Ajouter une nouvelle balise', extra=[('Name', 'alb-prod-leman-TP-AC')], kp='Clé', vp='Valeur')
    r.mark('balises')
    await r.scroll(3000); await r.hold(1.0)
    await r.click(btn("Créer un équilibreur de charge", True)); await r.hold(6.0)
    r.mark('cree'); await r.hold(2.0)
    r.mark('attente-debut', accelere=6); await r.hold(120.0); r.mark('attente-fin')
