"""Module 12 : alarme sur les erreurs 5xx de l'ALB (plus de 5 en 1 minute), avec action SNS."""
from common import *

async def run(r):
    await r.goto('https://eu-north-1.console.aws.amazon.com/cloudwatch/home?region=eu-north-1#alarmsV2:create', wait=8); await r.hold(1.5)
    await r.click(btn('Sélectionner une métrique')); await r.hold(4.0)
    await r.type(lambda f: f.get_by_placeholder(re.compile('Filtrer par n’importe quelle métrique')), 'alb-prod-leman-TP-AC HTTPCode_ELB_5XX_Count'); await r.press('Enter', 4.0)
    r.mark('filtre')
    await r.click(lambda f: f.get_by_text(re.compile('Métriques par AppELB$')).first); await r.hold(2.5)
    await r.click(lambda f: f.get_by_role('checkbox', name=re.compile('HTTPCode_ELB_5XX_Count')).last); await r.hold(1.5)
    r.mark('metrique')
    await r.click(lambda f: f.get_by_role('button', name='Sélectionner une métrique').last); await r.hold(4.0)
    r.mark('conditions')
    await r.click(lambda f: f.locator('input[value=Moyenne]').first); await r.hold(1.2)
    await r.click(lambda f: f.get_by_role('option', name=re.compile('^Somme')).first); await r.hold(1.2)
    await r.click(btn('5 minutes')); await r.hold(1.2)
    await r.click(lambda f: f.get_by_role('option', name=re.compile('^1 minute')).first); await r.hold(1.2)
    r.mark('statistique')
    await r.scroll(700)
    await r.type(lambda f: f.locator('input[type=number]').first, '5'); await r.hold(1.0)
    r.mark('seuil')
    await r.scroll(900)
    await r.click(btn('Suivant', True)); await r.hold(3.0)
    r.mark('notifications')
    await r.click(lambda f: f.get_by_placeholder('Sélectionner une rubrique SNS').first); await r.hold(1.5)
    await r.click(lambda f: f.get_by_role('option', name=re.compile('sns-exploitation-leman-TP-AC')).first); await r.hold(1.5)
    r.mark('rubrique')
    await r.click(btn('Ajouter une notification')); await r.hold(1.5)
    r.mark('notif2')
    await r.click(lambda f: f.get_by_text('OK', exact=True).last); await r.hold(1.2)
    await r.click(lambda f: f.get_by_placeholder('Sélectionner une rubrique SNS').last); await r.hold(1.5)
    await r.click(lambda f: f.get_by_role('option', name=re.compile('sns-exploitation-leman-TP-AC')).first); await r.hold(1.5)
    r.mark('retour-ok')
    await r.scroll(3000)
    await r.click(btn('Suivant', True)); await r.hold(3.0)
    await r.type(lambda f: f.locator('input[type=text]').first, 'alarm-5xx-portail-TP-AC'); await r.hold(0.8)
    r.mark('nom')
    await r.scroll(3000)
    await r.click(btn('Suivant', True)); await r.hold(3.0)
    r.mark('apercu'); await r.hold(2.0)
    await r.scroll(3000)
    await r.click(btn('Créer une alarme', True)); await r.hold(5.0)
    r.mark('creee'); await r.hold(2.5)
