"""Module 4 : creation du pare-feu (un endpoint dans sub-fw-1a) avec la politique, puis attente de l'etat Pret."""
from common import *
import time

async def run(r):
    await r.goto(vpc_url('NetworkFirewalls:'), wait=5)
    await r.hold(1.5)
    await r.click(btn('Créer un pare-feu')); await r.hold(2.5)
    await r.type(ph('Saisir le nom du pare-feu'), 'nfw-prod-leman-TP-AC'); await r.hold(0.6)
    await r.click(btn('Suivant', True)); await r.hold(2.5)
    await r.click('input[value=source-preservation]'); await r.hold(1.2)
    await r.click(btn('Sélectionner un VPC')); await r.hold(1.0)
    await r.click(lambda f: f.get_by_role('option', name=re.compile('vpc-prod-leman-TP-AC')).first); await r.hold(1.5)
    await r.click(btn('Choisissez les zones de disponibilité')); await r.hold(1.0)
    await r.click(lambda f: f.get_by_role('option', name=re.compile('eu-north-1a')).first); await r.hold(1.2)
    await r.click(btn('Sélectionner un sous-réseau')); await r.hold(1.0)
    await r.click(lambda f: f.get_by_role('option', name=re.compile('sub-fw-1a-TP-AC')).first); await r.hold(1.2)
    await r.click(btn('Choisir un type d’adresse IP')); await r.hold(1.0)
    await r.click(lambda f: f.get_by_role('option', name=re.compile('IPv4')).first); await r.hold(1.2)
    r.mark('capacite')
    await r.click(btn('Suivant', True)); await r.hold(2.0)
    await r.click(btn('Suivant', True)); await r.hold(2.5)
    r.mark('politique')
    await r.click('input[value=associateExistingPolicy]'); await r.hold(1.2)
    await r.click(lambda f: f.get_by_role('button', name=re.compile('Sélectionner|Choisir')).filter(visible=True).first); await r.hold(1.2)
    await r.click(lambda f: f.get_by_role('option', name=re.compile('policy-prod-leman-TP-AC')).first); await r.hold(1.5)
    r.mark('politique-choisie')
    await r.scroll(900)
    await r.click(btn('Suivant', True)); await r.hold(2.5)
    await tags(r, 'prod', start=0, add='Ajouter une balise', kp='Entrer la clé', vp='Entrer la valeur', extra=[('Name', 'nfw-prod-leman-TP-AC')])
    r.mark('balises')
    await r.scroll(1000)
    await r.click(btn('Suivant', True)); await r.hold(2.5)
    r.mark('verification'); await r.hold(2.0)
    await r.scroll(3000)
    await r.click(btn('Créer un pare-feu', True)); await r.hold(5.0)
    r.mark('cree')
