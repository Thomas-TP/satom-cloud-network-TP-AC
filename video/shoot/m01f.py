"""Module 1 : lancement de app-01 (sous-reseau prive, sans adresse publique) avec une mini-API sur le port 8080."""
from common import *

USERDATA = "#!/bin/bash\ncat > /opt/app.py <<'PYEOF'\nfrom http.server import BaseHTTPRequestHandler, HTTPServer\nclass H(BaseHTTPRequestHandler):\n    def do_GET(self):\n        body = b'app-01 TP-AC /api/health'\n        self.send_response(200); self.send_header('Content-Length', str(len(body))); self.end_headers(); self.wfile.write(body)\n    def log_message(self, *a): pass\nHTTPServer(('0.0.0.0', 8080), H).serve_forever()\nPYEOF\ncat > /etc/systemd/system/app.service <<'UNITEOF'\n[Unit]\nDescription=API app-01\nAfter=network.target\n[Service]\nExecStart=/usr/bin/python3 /opt/app.py\nRestart=always\n[Install]\nWantedBy=multi-user.target\nUNITEOF\nsystemctl daemon-reload\nsystemctl enable --now app\n"

async def run(r):
    await r.goto(ec2_url('LaunchInstances:'), wait=5)
    await r.hold(1.5)
    await r.type(ph('par exemple, Mon serveur web'), 'app-01-TP-AC'); await r.hold(0.8)
    await r.click(txt('Ajouter des balises supplémentaires')); await r.hold(1.0)
    await tags(r, 'prod', start=1, kp='@Clé de balise', vp='@Valeur de balise')
    r.mark('nom-balises'); await r.hold(1.0)
    await r.scroll(900); await r.hold(1.0)
    r.mark('ami-type'); await r.hold(2.0)
    await r.scroll(700); await r.hold(0.8)
    await r.click(txt('Sélectionnez', True)); await r.hold(1.0)
    await r.click(opt(re.compile('Continuer sans'))); await r.hold(1.0)
    r.mark('paire-cles')
    await r.click(btn('Modifier')); await r.hold(1.5)
    r.mark('reseau')
    await r.click('button:has-text("vpc-05507")'); await r.hold(1.0)
    await r.click(txt('vpc-prod-leman-TP-AC')); await r.hold(3.0)
    r.mark('vpc-sous-reseau')
    await r.click(txt('Sélectionner un groupe de sécurité existant')); await r.hold(1.0)
    await r.scroll(300)
    await r.click(txt('Sélectionner les groupes de sécurité', True)); await r.hold(1.0)
    await r.click(lambda f: f.get_by_role('option', name=re.compile('default')).first); await r.hold(1.2)
    r.mark('sg')
    await r.click(txt('Configuration réseau avancée')); await r.hold(1.5)
    r.mark('reseau-avance')
    await r.type(ph('123.123.123.1'), '10.20.1.10'); await r.hold(1.0)
    r.mark('ip-fixe')
    await r.scroll(1400); await r.hold(0.8)
    await r.click(txt('Détails avancés')); await r.hold(1.5)
    await r.scroll(500); await r.hold(0.8)
    await r.scroll(900)
    await r.type(lambda f: f.locator('textarea').filter(visible=True).last, USERDATA, delay=12); await r.hold(1.5)
    r.mark('donnees-utilisateur')
    await r.scroll(-900); await r.hold(0.5)
    await r.click(lambda f: f.get_by_text("Profil d'instance IAM", exact=True).first.locator('xpath=following::button[1]')); await r.hold(1.2)
    await r.click(lambda f: f.get_by_role('option', name=re.compile('TP-AC-ec2-ssm-role')).first); await r.hold(1.2)
    r.mark('profil-iam')
    await r.click(btn("Lancer l'instance")); await r.hold(6.0)
    r.mark('lancee'); await r.hold(2.5)
