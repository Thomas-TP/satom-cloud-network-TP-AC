"""Module 10 : enregistrements de basculement dans la vraie zone leman.thomastp.ch : portefeuilles (alias vers l'ALB, principal, avec la surveillance de l'etat) et un secours statique."""
from common import *
from m10c import zone_pub

async def run(r):
    await r.goto('https://us-east-1.console.aws.amazon.com/route53/v2/hostedzones#ListRecordSets/' + zone_pub(), wait=6); await r.hold(2.0)
    await r.click(btn('Créer un enregistrement', True)); await r.hold(3.0)
    await r.type(ph('subdomain'), 'portefeuilles'); await r.hold(0.6)
    await r.click(lambda f: f.get_by_text('Alias', exact=True).first); await r.hold(1.5)
    r.mark('alias')
    await r.click(btn('Choisir un point de terminaison')); await r.hold(1.2)
    await r.click(lambda f: f.get_by_role('option', name=re.compile('application et Classic')).first); await r.hold(1.5)
    await r.click(btn('Choisir une région')); await r.hold(1.2)
    await r.click(lambda f: f.get_by_role('option', name=re.compile('Stockholm')).first); await r.hold(1.5)
    r.mark('region')
    await r.click(lambda f: f.get_by_placeholder('Choisir un équilibreur de charge')); await r.hold(1.5)
    await r.click(lambda f: f.get_by_role('option', name=re.compile('alb-prod-leman-TP-AC')).first); await r.hold(1.5)
    r.mark('alb')
    await r.click(btn('Routage simple')); await r.hold(1.2)
    await r.click(lambda f: f.get_by_role('option', name=re.compile('Basculement')).first); await r.hold(1.5)
    r.mark('basculement')
    await r.click(btn('Choisir le type')); await r.hold(1.2)
    await r.click(lambda f: f.get_by_role('option', name=re.compile('Principal')).first); await r.hold(1.2)
    await r.click(lambda f: f.get_by_placeholder('Choisir une vérification de l’état')); await r.hold(1.5)
    await r.click(lambda f: f.get_by_role('option', name=re.compile('hc-portail-TP-AC|9da1f051')).first); await r.hold(1.5)
    await r.type(lambda f: f.get_by_placeholder('Équilibreur de charge USA Ouest'), 'portefeuilles-principal'); await r.hold(0.8)
    r.mark('principal')
    await r.click(btn('Ajouter un autre enregistrement', True)); await r.hold(1.5)
    await r.scroll(500)
    await r.type(lambda f: f.get_by_placeholder('subdomain').nth(1), 'portefeuilles'); await r.hold(0.5)
    await r.type(lambda f: f.locator('textarea').first, '203.0.113.50'); await r.hold(0.8)
    r.mark('secours')
    await r.click(lambda f: f.get_by_role('button', name='Routage simple').last); await r.hold(1.2)
    await r.click(lambda f: f.get_by_role('option', name=re.compile('Basculement')).first); await r.hold(1.5)
    await r.click(lambda f: f.get_by_role('button', name='Choisir le type').last); await r.hold(1.2)
    await r.click(lambda f: f.get_by_role('option', name=re.compile('Secondaire')).first); await r.hold(1.2)
    await r.type(lambda f: f.get_by_placeholder('Équilibreur de charge USA Ouest').last, 'portefeuilles-secours'); await r.hold(0.8)
    r.mark('secondaire')
    await r.scroll(900)
    await r.click(btn('Créer des enregistrements', True)); await r.hold(5.0)
    r.mark('crees'); await r.hold(2.5)
