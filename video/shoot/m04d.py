"""Module 4 : politique de pare-feu (ordre strict, abandon par defaut des flux etablis, alertes) avec le groupe de regles de domaines."""
from common import *

async def run(r):
    await r.goto(vpc_url('NetworkFirewallPolicies:'), wait=5)
    await r.hold(1.5)
    await r.click(lambda f: f.get_by_role('button', name=re.compile('^Créer une stratégie')).first); await r.hold(2.5)
    await r.click('input[value=V1]'); await r.hold(1.0)
    await r.click(btn('Passer au mode Classique')); await r.hold(1.5)
    await r.type(ph('Saisir le nom de la politique de pare-feu'), 'policy-prod-leman-TP-AC'); await r.hold(0.6)
    await r.click(lambda f: f.locator('input[type=checkbox]').first); await r.hold(1.0)   # pas de defense active (payante)
    await r.scroll(700)
    await tags(r, 'prod', start=0, add='Ajouter une balise', kp='Entrer la clé', vp='Entrer la valeur', extra=[('Name', 'policy-prod-leman-TP-AC')])
    r.mark('nom')
    await r.scroll(900)
    await r.click(btn('Suivant', True)); await r.hold(2.0)
    await r.click(btn('Suivant', True)); await r.hold(2.5)
    r.mark('ordre-strict')
    await r.click('input[value="aws:drop_established"]'); await r.hold(1.0)
    await r.click(txt('Alerte établie', True)); await r.hold(1.0)
    r.mark('abandon-etabli')
    await r.click(btn('Ajouter des groupes de règles avec état')); await r.hold(2.0)
    await r.click(lambda f: f.locator('tr', has_text='rg-depots-autorises-TP-AC').get_by_role('checkbox')); await r.hold(1.2)
    await r.click(btn('Ajouter des groupes de règles', True)); await r.hold(2.0)
    r.mark('groupe-ajoute')
    await r.scroll(1200)
    await r.click(btn('Suivant', True)); await r.hold(2.0)
    await r.click(btn('Suivant', True)); await r.hold(2.5)
    r.mark('verification'); await r.hold(2.0)
    await r.scroll(2500)
    await r.click(btn('Créer une stratégie de pare-feu', True)); await r.hold(5.0)
    r.mark('creee'); await r.hold(2.0)
